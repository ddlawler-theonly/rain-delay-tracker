// Copies the web app (repo root = the GitHub Pages site) -> www/, switches it to the App Store build
// (CONFIG.STORE = true: starts empty, "Load sample job", no preloaded job sites or Lauder Rd data),
// bundles the Capacitor bridge into www/js/native.js and removes the service worker.
import { build } from 'esbuild';
import fs from 'node:fs'; import path from 'node:path';
import './apply-config.mjs';
const root = path.resolve(import.meta.dirname, '..'); const web = path.resolve(root, '..'); const www = path.join(root, 'www');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'raindelay.config.json'), 'utf8'));
fs.rmSync(www, { recursive: true, force: true });
const skip = new Set(['ios-app', 'appstore', '.github', '.git', 'node_modules', 'test.mjs', 'README.md', '.nojekyll', 'sw.js']);
const copy = (src, dst) => { fs.mkdirSync(dst, { recursive: true }); for (const e of fs.readdirSync(src, { withFileTypes: true })) { if (skip.has(e.name) || e.name.endsWith('.b64')) continue; const s = path.join(src, e.name), d = path.join(dst, e.name); e.isDirectory() ? copy(s, d) : fs.copyFileSync(s, d); } };
copy(web, www);
// Store build flag
fs.writeFileSync(path.join(www, 'js/config.js'), `// Generated by ios-app/scripts/build-web.mjs (App Store build)\nexport const CONFIG = { STORE: ${cfg.store !== false}, VERSION: '${cfg.version}' };\n`);
// Strip Derek's job sites and the Lauder Rd history from the store bundle
if (cfg.store !== false) {
  let d = fs.readFileSync(path.join(www, 'js/data.js'), 'utf8');
  d = d.replace(/export const SEED_DAYS=\[[\s\S]*?\];\n/, 'export const SEED_DAYS=[];\n').replace(/export const PRESET_JOBS=\[[\s\S]*?\];\n/, 'export const PRESET_JOBS=[];\n').replace(/export const SEED_JOB=\{[\s\S]*?\};\n/, 'export const SEED_JOB=null;\n');
  // Not bare 'Lauder': "Fort Lauderdale" is a real Florida station name in the US-wide list.
  if (/Lauder Rd|Aldine|Bergamo|Tellepson|Ig0057/i.test(d)) throw new Error('private job data still in store bundle');
  fs.writeFileSync(path.join(www, 'js/data.js'), d);
  for (const f of fs.readdirSync(path.join(www, 'js'))) if (/Lauder Rd|Aldine Bender|Tellepson|Ig0057/i.test(fs.readFileSync(path.join(www, 'js', f), 'utf8'))) throw new Error('private job data in js/' + f);
}
await build({ entryPoints: [path.join(root, 'src/native-entry.js')], bundle: true, format: 'iife', target: ['safari15'], minify: true, outfile: path.join(www, 'js/native.js') });
let html = fs.readFileSync(path.join(www, 'index.html'), 'utf8');
html = html.replace('<script type="module" src="js/app.js"></script>', '<script src="js/native.js"></script>\n<script type="module" src="js/app.js"></script>');
html = html.replace(/<title>.*?<\/title>/, `<title>${cfg.appName}</title>`);
fs.writeFileSync(path.join(www, 'index.html'), html);
console.log('www built (' + cfg.appName + ' ' + cfg.version + ', store=' + (cfg.store !== false) + ')');
